/** Number of lit bits in a glyph (used by tests). */
export function glyphPixels(ch) {
  const gl = GLYPHS[String(ch).toUpperCase()];
  if (!gl) return 0;
  let n = 0;
  for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (gl[r] & (1 << (4 - c))) n++;
  return n;
}

/**
 * Blit text into the packed buffer (0xAABBGGRR).
 * @param {Uint32Array} buf
 * @param {number} W buffer width
 * @param {string} text
 * @param {number} x left pixel
 * @param {number} y top pixel
 * @param {number} s scale factor (1 = crisp 5x7)
 * @param {number} col packed color (0xAABBGGRR)
 */
export function blit(buf, W, text, x, y, s, col) {
  const H = buf.length / W | 0;
  for (let i = 0; i < text.length; i++) {
    const gl = GLYPHS[text[i]] || GLYPHS[text[i].toUpperCase()];
    if (!gl) continue;
    const x0 = x + i * 6 * s;
    for (let r = 0; r < 7; r++) {
      const row = gl[r];
      if (!row) continue;
      for (let c = 0; c < 5; c++) {
        if (!(row & (1 << (4 - c)))) continue;
        for (let dy = 0; dy < s; dy++) {
          const py = y + r * s + dy;
          if (py < 0 || py >= H) continue;
          for (let dx = 0; dx < s; dx++) {
            const px = x0 + c * s + dx;
            if (px >= 0 && px < W) buf[py * W + px] = col;
          }
        }
      }
    }
  }
}

/** Centered blit: x computed so a string of n chars lands mid-buffer. */
export function blitCenter(buf, W, text, y, s, col) {
  blit(buf, W, text, Math.max(0, (W - text.length * 6 * s + s) / 2) | 0, y, s, col);
}
